// @vitest-environment node
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { load } from 'js-yaml';
import { apiComponents, generateTypes, outputDir, schemaDir, specFile } from '../../scripts/gen-types.mjs';

interface Component {
    type?: string;
    required?: string[];
    properties?: Record<string, Component>;
    items?: Component;
    $ref?: string;
}

const typeNames = new Set([...Object.values(apiComponents), 'review-stored-op']);

/** Each property below `node` as a dotted path, marked whether it is required; a component generated as its own type is not entered. */
function expectedProperties(schemas: Record<string, Component>, node: Component, prefix = ''): Record<string, boolean> {
    const name = node.$ref?.replace('#/components/schemas/', '');
    if (name !== undefined && typeNames.has(name)) return {};
    const { properties, required = [] } = name === undefined ? node : schemas[name];
    const out: Record<string, boolean> = {};
    for (const [property, child] of Object.entries(properties ?? {})) {
        out[`${prefix}${property}`] = required.includes(property);
        Object.assign(out, expectedProperties(schemas, child.items ?? child, `${prefix}${property}.`));
    }
    return out;
}

/** The properties of the interface `name` in `source` as dotted paths, each marked whether it is required. */
function declared(source: string, name: string) {
    const body = source.match(new RegExp(`^export interface ${name} \\{\\n([\\s\\S]*?)^\\}`, 'm'))?.[1];
    if (body === undefined) return undefined;
    const parents: string[] = [];
    const out: Record<string, boolean> = {};
    for (const [, indent, property, optional] of body.matchAll(/^( +)(\w+)(\??): /gm)) {
        const depth = indent.length / 4 - 1;
        parents[depth] = property;
        out[parents.slice(0, depth + 1).join('.')] = optional === '';
    }
    return out;
}

describe('generated contract types', () => {
    it('match the schemas and spec components they are generated from, with no other file beside them', async () => {
        const generated = await generateTypes();
        expect(readdirSync(outputDir).sort()).toEqual(Object.keys(generated).sort());
        for (const [file, content] of Object.entries(generated)) {
            expect(readFileSync(path.join(outputDir, file), 'utf8')).toBe(content);
        }
    });

    it('name the review JSON Schemas and the spec in their banner', async () => {
        for (const [file, content] of Object.entries(await generateTypes())) {
            expect(content.split('\n')[0], file).toMatch(
                /^\/\* Generated by .*JSON Schemas.* and .*OpenAPI spec.*Do not edit\. \*\/$/
            );
        }
    });

    it('declare each API type with exactly the required fields of its spec component, nested ones included', async () => {
        const source = (await generateTypes())['review-api.ts'];
        const { components } = load(readFileSync(specFile, 'utf8')) as {
            components: { schemas: Record<string, Component> };
        };
        for (const [name, component] of Object.entries(apiComponents)) {
            const expected = expectedProperties(components.schemas, components.schemas[component]);
            expect(declared(source, name), name).toEqual(expected);
        }
        expect(declared(source, 'PaperPage')).toMatchObject({ 'metadata.total_count': true });
        expect(declared(source, 'ReviewSummary')).toMatchObject({ 'set_aside.reason': true, set_aside: false });
    });

    it('export the batch bounds of the review-ops schema', async () => {
        const ops = (await import('./generated/review-ops')) as Record<string, unknown>;
        const { minItems, maxItems } = JSON.parse(readFileSync(path.join(schemaDir, 'review-ops.schema.json'), 'utf8'))
            .properties.ops;
        expect(ops).toMatchObject({ BATCH_MIN_OPS: minItems, BATCH_MAX_OPS: maxItems });
        expect((await generateTypes())['review-ops.ts']).toContain(`export const BATCH_MAX_OPS = ${maxItems};`);
    });
});
