import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile, compileFromFile } from 'json-schema-to-typescript';
import { load } from 'js-yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
export const schemaDir = path.resolve(here, '../../backend/neurostore/review/schema');
export const specFile = path.resolve(here, '../../backend/neurostore/openapi/neurostore-openapi.yml');
export const outputDir = path.resolve(here, '../src/contract/generated');

const schemas = ['review-bundle', 'review-ops'];
const banner =
    '/* Generated by scripts/gen-types.mjs from the review JSON Schemas (store/backend/neurostore/review/schema) and the OpenAPI spec (store/backend/neurostore/openapi/neurostore-openapi.yml). Do not edit. */';
export const apiComponents = {
    ReviewSummary: 'review-summary',
    OpResult: 'review-op-result',
    ErrorBody: 'ErrorResponse',
    PaperSummary: 'review-source',
    PaperPage: 'review-source-list',
    ReviewerProgress: 'review-progress',
    Assignee: 'review-assignee',
    Me: 'review-me',
    ReviewerList: 'review-reviewer-list',
};
const typeOf = Object.fromEntries(Object.entries(apiComponents).map(([name, component]) => [component, name]));
const style = { singleQuote: true, tabWidth: 4, printWidth: 120 };

/**
 * A spec component as plain JSON Schema: a ref to another generated component named by its type, other refs inlined,
 * stored ops taken from the bundle schema, nullable as a type union.
 */
function inlined(node, components) {
    if (Array.isArray(node)) return node.map((item) => inlined(item, components));
    if (node === null || typeof node !== 'object') return node;
    if (typeof node.$ref === 'string') {
        const name = node.$ref.replace('#/components/schemas/', '');
        if (name === 'review-stored-op') return { $ref: 'review-bundle.schema.json#/$defs/StoredOp' };
        if (typeOf[name]) return { tsType: typeOf[name] };
        return inlined(components[name], components);
    }
    const { nullable, ...rest } = node;
    const out = Object.fromEntries(Object.entries(rest).map(([key, value]) => [key, inlined(value, components)]));
    if (nullable && typeof out.type === 'string') out.type = [out.type, 'null'];
    return out;
}

async function apiTypes() {
    const { components } = load(readFileSync(specFile, 'utf8'));
    const parts = [];
    for (const [name, component] of Object.entries(apiComponents)) {
        parts.push(
            await compile(inlined(components.schemas[component], components.schemas), name, {
                cwd: schemaDir,
                bannerComment: '',
                additionalProperties: false,
                declareExternallyReferenced: false,
                style,
            })
        );
    }
    return `${banner}\n\nimport type { StoredOp } from './review-bundle';\n\n${parts.join('\n')}`;
}

function batchBounds() {
    const { minItems, maxItems } = JSON.parse(readFileSync(path.join(schemaDir, 'review-ops.schema.json'), 'utf8'))
        .properties.ops;
    const bounds = { BATCH_MIN_OPS: minItems, BATCH_MAX_OPS: maxItems };
    return Object.entries(bounds)
        .filter(([, value]) => value !== undefined)
        .map(([name, value]) => `export const ${name} = ${value};\n`)
        .join('');
}

export async function generateTypes() {
    const out = {};
    for (const name of schemas) {
        out[`${name}.ts`] = await compileFromFile(path.join(schemaDir, `${name}.schema.json`), {
            cwd: schemaDir,
            bannerComment: banner,
            additionalProperties: false,
            style,
        });
    }
    out['review-ops.ts'] += `\n${batchBounds()}`;
    out['review-api.ts'] = await apiTypes();
    return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    mkdirSync(outputDir, { recursive: true });
    for (const [file, content] of Object.entries(await generateTypes())) {
        writeFileSync(path.join(outputDir, file), content);
    }
}
